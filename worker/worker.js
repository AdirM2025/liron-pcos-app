// (לדוגמה מגבלת שימוש זמנית על החיפוש), נופלים חזרה לקריאה בלי חיפוש - עדיף תשובה
// טובה מהידע הקבוע מאשר שגיאה.
async function callGemini(env, userMessage, useSearch) {
  const requestBody = {
    systemInstruction: { parts: [{ text: PERSONA_INSTRUCTIONS + "\n\n" + KNOWLEDGE_BASE }] },
    contents: [{ role: "user", parts: [{ text: userMessage }] }],
    generationConfig: { maxOutputTokens: 1000, temperature: 0.7 },
  };
  if (useSearch) requestBody.tools = [{ google_search: {} }];
  return fetch(`${GEMINI_URL}?key=${env.GEMINI_API_KEY}`, {
    method: "POST",
    headers: { "content-type": "application/json" },
    body: JSON.stringify(requestBody),
  });
}

export default {
  async fetch(request, env) {
    const origin = request.headers.get("Origin") || "";
    const headers = corsHeaders(origin);

    if (request.method === "OPTIONS") {
      return new Response(null, { headers });
    }
    if (request.method !== "POST") {
      return new Response(JSON.stringify({ text: "רק בקשות POST נתמכות." }), {
        status: 405,
        headers: { ...headers, "Content-Type": "application/json" },
      });
    }

    try {
      const body = await request.json();
      const prompt = String(body.prompt || "").slice(0, 4000);
      const context = body.context || {};

      if (!prompt) {
        return new Response(JSON.stringify({ text: "לא התקבלה שאלה." }), {
          status: 400,
          headers: { ...headers, "Content-Type": "application/json" },
        });
      }

      const userMessage = context && Object.keys(context).length
        ? `נתונים נלווים על המצב הנוכחי של לירון (JSON): ${JSON.stringify(context)}\n\nהשאלה או הבקשה של לירון: "${prompt}"`
        : prompt;

      // הערה: חיפוש חי (google_search) כבוי כברירת מחדל - במפתח API חינמי בלי חיוב מקושר
      // המכסה שלו כמעט אפסית וגרמה לשגיאות. במקום זה מאגר הידע הקבוע למעלה הורחב משמעותית.
      // אם בעתיד יקושר חיוב לפרויקט, אפשר להחזיר ל-true כדי להפעיל שוב חיפוש חי אמיתי.
      let geminiRes = await callGemini(env, userMessage, false);

      if (!geminiRes.ok) {
        const errText = await geminiRes.text();
        console.error("Gemini API error:", geminiRes.status, errText);
        return new Response(JSON.stringify({ text: "הייתה בעיה זמנית בשירות. נסי שוב עוד רגע 💗" }), {
          status: 200,
          headers: { ...headers, "Content-Type": "application/json" },
        });
      }

      const data = await geminiRes.json();
      let text = data?.candidates?.[0]?.content?.parts?.[0]?.text?.trim() || "";

      // ניקוי בטיחות: הסרת סימני markdown, ותווים משפות אחרות שלפעמים "מתערבבים" בטעות (באג נדיר של המודל)
      text = text.replace(/\*\*/g, "").replace(/[#*_`]/g, "");
      text = text.replace(/[Ѐ-ӿ؀-ۿ]/g, "").replace(/\s{2,}/g, " ").trim();

      if (!text) {
        text = "לא הצלחתי לנסח תשובה כרגע, נסי לשאול שוב במילים קצת אחרות.";
      }

      return new Response(JSON.stringify({ text }), {
        headers: { ...headers, "Content-Type": "application/json" },
      });
    } catch (e) {
      console.error("Worker error:", e);
      return new Response(JSON.stringify({ text: "שגיאה זמנית. נסי שוב בעוד רגע." }), {
        status: 200,
        headers: { ...headers, "Content-Type": "application/json" },
      });
    }
  },
};
